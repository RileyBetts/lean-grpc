Copyright © 2026, Riley Betts Ltd (rileybetts.ai)
Generated by protoc-gen-lean4-grpc (descriptor path) — do not edit.
Regenerate with: ./scripts/gen-helloworld.sh
Released under Apache 2.0 license as described in the file LICENSE.
-/
"""
# Drop whatever header the emitter wrote and replace with the checked-in banner.
if content.startswith("/-"):
    end = content.find("-/")
    if end >= 0:
        content = content[end + 2 :].lstrip("\n")
open(sys.argv[2], "w").write(header + content)
print(f"wrote {sys.argv[2]}")
