import sys

def read_varint(b, i):
    x = s = 0
    while True:
        c = b[i]; i += 1
        x |= (c & 0x7F) << s
        if not (c & 0x80):
            return x, i
        s += 7

def decode_message(buf):
    i = 0
    fields = {}
    while i < len(buf):
        tag, i = read_varint(buf, i)
        field, wt = tag >> 3, tag & 7
        if wt == 0:
            v, i = read_varint(buf, i)
            fields.setdefault(field, []).append(v)
        elif wt == 2:
            ln, i = read_varint(buf, i)
            payload = buf[i : i + ln]
            i += ln
            fields.setdefault(field, []).append(payload)
        else:
            raise SystemExit(f"unsupported wire type {wt}")
    return fields

data = open(sys.argv[1], "rb").read()
top = decode_message(data)
file_msg = decode_message(top[15][0])
content = file_msg[15][0].decode("utf-8")
# Ensure namespace close is explicit for the checked-in module path.
if content.rstrip().endswith("end"):
    content = content.rstrip()[:-3] + "end helloworld\n"
